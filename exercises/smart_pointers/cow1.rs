//本练习探讨 Cow 或 Clone-On-Write 类型。牛是一个
//写入时克隆智能指针。它可以包含并提供对以下内容的不可变访问
//借用数据，并在发生突变或所有权时延迟克隆数据
//必填。该类型旨在通过以下方式处理一般借用的数据
//借用特征。
//
//这个练习的目的是向您展示将数据传递给 Cow 时会发生什么。
//通过检查 Cow::Owned(_) 和 Cow::Borrowed(_) 来修复单元测试
